  await t.test('Nixpacks configuration fetch and update SDK methods', async () => {
    let fetchCount = 0;
    let putBody: any = null;

    const mockFetch = async (url: string | URL | Request, init?: RequestInit) => {
      fetchCount++;
      if (init?.method === 'PUT') {
        putBody = JSON.parse(String(init.body));
        return new Response(JSON.stringify({
          deploymentId: 'dep-999',
          builder: 'NIXPACKS',
          nixpacksConfig: putBody,
          effectiveToml: generateNixpacksToml(putBody),
        }), { status: 200, headers: { 'Content-Type': 'application/json' } });
      }

      return new Response(JSON.stringify({
        deploymentId: 'dep-999',
        builder: 'AUTO',
        rootDir: null,
        nixpacksConfig: {},
        effectiveToml: '# Generated by ShanuTechX Platform\n',
      }), { status: 200, headers: { 'Content-Type': 'application/json' } });
    };

    const client = new ShanutechxClient({
      baseUrl: 'http://localhost:4000',
      token: 'test-token',
      fetch: mockFetch as any,
    });

    const current = await client.deployments.getNixpacksConfig('dep-999');
    assert.equal(current.deploymentId, 'dep-999');

    const updated = await client.deployments.updateNixpacksConfig('dep-999', {
      providers: ['python'],
      phases: {
        setup: { nixPkgs: ['python311'] },
      },
    });

    assert.equal(updated.deploymentId, 'dep-999');
    assert.deepEqual(putBody.providers, ['python']);
    assert.ok(updated.effectiveToml.includes('providers = ["python"]'));
  });
